def test_original_item_mutations_leave_parent_and_unrelated_children_unchanged(sql_connection):
    connection, _ = sql_connection
    maps = seed(connection)
    identifier = maps["contractId"][1]
    parent = TABLES["Contracts"]
    before = dict(connection.execute(sa.select(parent).where(parent.c.contractId == identifier)).mappings().one())
    form = mapped(REFERENCE["fullForm"], maps)
    add_contract_interment(connection, form, ACTOR, audit_enabled=True)
    update_contract_interment(connection, {**form, "intermentNumber": 1}, EDITOR, audit_enabled=True)
    delete_contract_interment(connection, identifier, 1, EDITOR, audit_enabled=True)
    service = {"contractId": identifier, "serviceTypeId": maps["serviceTypeId"][1]}
    add_contract_service_type(connection, service, ACTOR, audit_enabled=True)
    update_contract_service_type(connection, {**service, "contractServiceDetails": "Synthetic details"}, EDITOR, audit_enabled=True)
    delete_contract_service_type(connection, identifier, service["serviceTypeId"], EDITOR, audit_enabled=True)
    after = dict(connection.execute(sa.select(parent).where(parent.c.contractId == identifier)).mappings().one())
    assert (before == after) == REFERENCE["sideEffects"]["parentUnchanged"]
    assert set(connection.scalars(sa.select(TABLES["AuditLog"].c.updateTable))) == set(REFERENCE["sideEffects"]["auditTables"])
    for name, count in REFERENCE["sideEffects"]["unrelatedCounts"].items():
        assert connection.scalar(sa.select(sa.func.count()).select_from(TABLES[name])) == count


