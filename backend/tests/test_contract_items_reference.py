def test_original_interment_repeat_delete_no_update_deleted_and_max_number_including_deleted(sql_connection):
    connection, _ = sql_connection
    maps = seed(connection)
    form = mapped(REFERENCE["fullForm"], maps)
    identifier = maps["contractId"][1]
    for case in REFERENCE["lifecycle"]:
        action = case["action"]
        if action == "add":
            result = add_contract_interment(connection, form, ACTOR, audit_enabled=True)
        elif action == "delete":
            result = delete_contract_interment(connection, identifier, 1, EDITOR, audit_enabled=True)
        elif action in ("updateDeleted", "updateMissing"):
            update = {**form, "intermentNumber": 1 if action == "updateDeleted" else 999}
            if action == "updateDeleted":
                update["deceasedName"] = "Must stay deleted"
            result = update_contract_interment(connection, update, EDITOR, audit_enabled=True)
        elif action == "deleteMissing":
            result = delete_contract_interment(connection, identifier, 999, EDITOR, audit_enabled=True)
        else:
            result = add_contract_interment(connection, {**form, "contractId": maps["contractId"][2]}, ACTOR, audit_enabled=True)
        assert result == case["result"], action
        assert raw(connection, "ContractInterments", maps) == case["rows"], action
        assert normalize(get_contract_interments(connection, identifier), maps) == case["retrieved"], action
    assert_audit(connection, maps, REFERENCE["lifecycleAudit"])


