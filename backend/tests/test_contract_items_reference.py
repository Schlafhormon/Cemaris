@pytest.mark.parametrize("case", REFERENCE["handlers"])
def test_original_handler_responses_and_documented_invalid_input_boundary(source_handler_app, case):
    app, maps = source_handler_app
    if case["existing"]:
        with app.state.db_engine.begin() as connection:
            if "Interment" in case["handler"]:
                add_contract_interment(connection, mapped(REFERENCE["fullForm"], maps), ACTOR)
            else:
                add_contract_service_type(connection, mapped({"contractId": 1, "serviceTypeId": 1,
                    "contractServiceDetails": "Synthetic original HTTP"}, maps), ACTOR)
    with TestClient(app) as client:
        csrf = client.get("/api/session").json()["csrfToken"]
        login = client.post("/api/login", json={"username": EDITOR, "password": "synthetic-password"}, headers={"X-CSRF-Token": csrf})
        assert login.status_code == 200, login.text
        options = client.get("/api/contracts/meta?lng=en").json()["options"]
        for key in ("deathAgePeriods", "purchaserRelationships"):
            assert options[key] == REFERENCE["dataLists"][key]
        response = client.post("/api/contracts/" + case["handler"], json=mapped(case["body"], maps),
            headers={"X-CSRF-Token": login.json()["csrfToken"]})
        if case["expected"]["status"] == 500:
            # Source throws on incomplete input. The port deliberately reports
            # a controlled validation error and retains the original row.
            assert response.status_code == 400, response.text
            assert response.json()["code"] == "invalid_contract_item"
            assert response.json()["success"] is False
        else:
            assert response.status_code == case["expected"]["status"], response.text
            body = normalize(response.json(), maps)
            if case["expected"]["body"]["success"]:
                assert body == case["expected"]["body"]
            else:
                # Failed interment deletion also includes the shared error
                # envelope; the original status/message/success are retained.
                assert {key: body[key] for key in case["expected"]["body"]} == case["expected"]["body"]
