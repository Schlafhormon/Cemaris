def mapped(values, maps):
    result = {}
    for key, value in values.items():
        if key.startswith("workOrderMilestone") and "_" in key:
            prefix, suffix = key.rsplit("_", 1)
            key = prefix + "_" + str(maps["workOrderMilestoneTypeId"].get(int(suffix), int(suffix)))
            if prefix == "workOrderMilestoneId" and value not in (None, ""):
                value = maps["workOrderMilestoneTypeId"].get(int(value), value)
        elif key == "parentCemeteryId" and value not in (None, ""):
            value = maps["cemeteryId"].get(value, value)
        elif key in maps and value not in (None, ""):
            source = int(value) if isinstance(value, str) and value.isdigit() else value
            value = maps[key].get(source, value)
        result[key] = value
    return result


def insert(connection, name, values):
    table = TABLES[name]
    values = {"recordCreate_username": ACTOR, "recordCreate_timeMillis": 1,
        "recordUpdate_username": ACTOR, "recordUpdate_timeMillis": 1, **values}
    result = connection.execute(table.insert().values(**values))
    key = next((column.name for column in table.c if column.identity is not None), None)
    return (key, result.inserted_primary_key[0]) if key else (None, None)


def seed(connection):
    maps = {}
    for item in REFERENCE["seed"]:
        key, actual = insert(connection, item["table"], mapped(item["values"], maps))
        if key:
            maps.setdefault(key, {})[item["id"]] = actual
    return maps


def normalize(value, maps):
    if isinstance(value, list):
        return [normalize(item, maps) for item in value]
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            if key.startswith("record") and key != "recordIndex":
                continue
            if key in maps and not isinstance(item, (dict, list)):
                result[key] = {actual: source for source, actual in maps[key].items()}.get(item, item)
            else:
                result[key] = normalize(item, maps)
        return result
    return value


def project(actual, expected):
    """Compare every source field; target shared APIs also expose extra metadata."""
    if isinstance(expected, list):
        assert len(actual) == len(expected)
        return [project(a, e) for a, e in zip(actual, expected, strict=True)]
    if isinstance(expected, dict):
        return {key: project(actual[key], value) for key, value in expected.items()}
    return actual


def raw(connection, name, maps):
    table = TABLES[name]
    rows = connection.execute(sa.select(table).order_by(*table.primary_key.columns)).mappings()
    return normalize([{**dict(row), "deleted": row["recordDelete_timeMillis"] is not None} for row in rows], maps)


def assert_audit(connection, maps, expected):
    rows = []
    for row in connection.execute(sa.select(TABLES["AuditLog"])).mappings():
        result = {key: row[key] for key in ("mainRecordType", "mainRecordId", "updateTable", "recordIndex", "updateField", "updateType", "updateUsername")}
        for key in ("fromValue", "toValue"):
            result[key] = normalize(json.loads(row[key]), maps) if row[key] is not None else None
            field_map = maps.get(result["updateField"], {})
            if not isinstance(result[key], (list, dict)):
                result[key] = {actual: source for source, actual in field_map.items()}.get(result[key], result[key])
        result["mainRecordId"] = str({actual: source for source, actual in maps["workOrderId"].items()}.get(int(result["mainRecordId"]), int(result["mainRecordId"])))
        if result["recordIndex"] is not None:
            child_key = {"WorkOrderMilestones": "workOrderMilestoneId", "WorkOrderComments": "workOrderCommentId",
                "WorkOrderBurialSites": "burialSiteId", "WorkOrderContracts": "contractId"}[result["updateTable"]]
            result["recordIndex"] = str({actual: source for source, actual in maps.get(child_key, {}).items()}.get(int(result["recordIndex"]), int(result["recordIndex"])))
        rows.append(result)
    key = lambda value: (value["updateTable"], value["recordIndex"] or "", value["updateField"], value["updateType"], json.dumps(value["fromValue"], sort_keys=True), json.dumps(value["toValue"], sort_keys=True))
    assert sorted(rows, key=key) == sorted(expected, key=key)


