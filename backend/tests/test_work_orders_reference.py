@pytest.mark.parametrize("case", REFERENCE["handlers"])
def test_original_work_order_handlers_success_workday_and_controlled_missing_boundaries(source_work_order_handler_app, case):
    app, maps = source_work_order_handler_app
    with TestClient(app) as client:
        csrf = client.get("/api/session").json()["csrfToken"]
        login = client.post("/api/login", json={"username": EDITOR, "password": "synthetic-password"}, headers={"X-CSRF-Token": csrf})
        assert login.status_code == 200, login.text
        response = client.post("/api/work-orders/" + case["handler"], json=mapped(case["body"], maps),
            headers={"X-CSRF-Token": login.json()["csrfToken"]})
        expected = case["expected"]["body"]
        if case["expected"]["status"] != 200:
            # Shared API errors are structured and require an active parent.
            # Raw helpers retain the source historical mutations separately.
            expected_status = 404 if case["body"].get("workOrderId") == 999 else case["expected"]["status"]
            assert response.status_code == expected_status, response.text
            assert response.json()["success"] is False
            return
        assert response.status_code == 200, response.text
        body = response.json()
        if case["handler"] == "doCreateWorkOrder":
            maps["workOrderId"][expected["workOrderId"]] = body["workOrderId"]
        elif case["handler"] == "doAddWorkOrderMilestone":
            maps["workOrderMilestoneId"][expected["workOrderMilestoneId"]] = body["workOrderMilestoneId"]
        elif case["handler"] == "doAddWorkOrderComment":
            maps["workOrderCommentId"] = {expected["workOrderComments"][0]["workOrderCommentId"]: body["workOrderComments"][0]["workOrderCommentId"]}
        body = normalize(body, maps)
        # Close converts the id to Number; reopen echoes the submitted string.
        # The port consistently returns the integral SQL identity instead.
        if isinstance(expected.get("workOrderId"), str):
            expected = {**expected, "workOrderId": int(expected["workOrderId"])}
        assert project(body, expected) == expected
