@pytest.fixture
def source_database():
    if not SOURCE.exists():
        pytest.skip("Optional fixed Sunrise reference checkout is unavailable")
    source = SOURCE.read_text(encoding="utf-8")
    audit_columns = re.search(
        r"const recordColumns = /\* sql \*/ `(.*?)`", source, re.S
    ).group(1)
    section = source.split("const sqlCreateStatements = [", 1)[1].split(
        "const initializingUser:", 1
    )[0]
    section = section.replace("${recordColumns}", audit_columns)
    # SQLite is the source oracle only, not a target persistence test.
    statements = re.findall(r"/\* sql \*/\s*(?:`([^`]+)`|'([^']+)')", section, re.S)
    connection = sqlite3.connect(":memory:")
    try:
        for template, single_quoted in statements:
            connection.execute(template or single_quoted)
        yield connection, section
    finally:
        connection.close()


def normalize_default(value: object) -> str | None:
    if value is None:
        return None
    return str(value).removeprefix("N")


def test_complete_model_and_sql_server_specific_decisions():
    assert len(TABLES) == 41
    assert len(metadata.tables) == 41
    assert SOURCE_TO_TARGET["SunriseSettings"] == "CemarisSettings"
    assert "SunriseSettings" not in TABLES
    assert all(table.schema == "dbo" for table in TABLES.values())
    assert not TABLES["AuditLog"].primary_key.columns
    assert TABLES["OrderForms"].c.orderFormId.identity is None
    assert TABLES["OrderForms"].c.orderFormId.autoincrement is False
    for table in TABLES.values():
        for column in table.columns:
            declared = column.info["source_declared_type"].upper()
            if declared == "INTEGER":
                assert isinstance(column.type, sa.BigInteger)
            if declared.startswith("DECIMAL"):
                assert isinstance(column.type, mssql.FLOAT)
                assert column.type.precision == 53
                assert column.type.asdecimal is False
            if declared.startswith(("VARCHAR", "CHAR")) or declared == "TEXT":
                assert isinstance(column.type, mssql.NVARCHAR)
                assert column.type.collation == TEXT_COLLATION
            if column.identity is not None:
                assert column.identity.start == 1
                assert column.identity.increment == 1


def test_all_source_columns_types_defaults_nullability_and_primary_keys(source_database):
    connection, _ = source_database
    names = {
        row[0]
        for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")
        if row[0] != "sqlite_sequence"
    }
    assert names == set(SOURCE_TO_TARGET)
    for source_name in names:
        table = TABLES[SOURCE_TO_TARGET[source_name]]
        columns = connection.execute(f'PRAGMA table_info("{source_name}")').fetchall()
        assert [row[1] for row in columns] == list(table.columns.keys()), source_name
        source_pk = [row[1] for row in sorted(columns, key=lambda row: row[5]) if row[5]]
        assert source_pk == list(table.primary_key.columns.keys()), source_name
        for _, name, declared, not_null, default, primary_key in columns:
            column = table.c[name]
            assert column.info["source_declared_type"].upper() == declared.upper()
            assert column.nullable is not bool(not_null or primary_key), (source_name, name)
            target_default = (
                column.server_default.arg
                if isinstance(column.server_default, sa.DefaultClause)
                else None
            )
            assert normalize_default(target_default) == normalize_default(default), (
                source_name, name
            )


def test_all_source_foreign_keys_and_indexes(source_database):
    connection, _ = source_database
    for source_name, target_name in SOURCE_TO_TARGET.items():
        table = TABLES[target_name]
        source_fks = {
            (row[3], SOURCE_TO_TARGET[row[2]], row[4])
            for row in connection.execute(f'PRAGMA foreign_key_list("{source_name}")')
        }
        target_fks = {
            (foreign_key.parent.name, foreign_key.column.table.name, foreign_key.column.name)
            for foreign_key in table.foreign_keys
        }
        assert source_fks == target_fks, source_name
        assert all(fk.ondelete is None and fk.onupdate is None for fk in table.foreign_keys)
        for _, index_name, unique, origin, _ in connection.execute(
            f'PRAGMA index_list("{source_name}")'
        ):
            source_columns = [
                row[2] for row in connection.execute(f'PRAGMA index_info("{index_name}")')
            ]
            if origin == "pk":
                continue
            if origin == "u":
                targets = [
                    constraint for constraint in table.constraints
                    if isinstance(constraint, sa.UniqueConstraint)
                ] + [index for index in table.indexes if index.unique]
                assert any(list(item.columns.keys()) == source_columns for item in targets)
            else:
                index = next(index for index in table.indexes if index.name == index_name)
                assert list(index.columns.keys()) == source_columns
                assert index.unique == bool(unique)
    assert sum(len(table.foreign_keys) for table in TABLES.values()) == 42
    assert sum(len(table.indexes) for table in TABLES.values()) == 20


def test_all_source_checks_are_preserved_as_table_constraints(source_database):
    _, section = source_database
    expected = []
    for source_name, body in re.findall(
        r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\)\s*(?:WITHOUT rowid)?\s*`", section, re.S
    ):
        checks = re.findall(r"CHECK\s*\(([^)]+)\)", body)
        actual = [
            str(constraint.sqltext) for constraint in TABLES[SOURCE_TO_TARGET[source_name]].constraints
            if isinstance(constraint, sa.CheckConstraint)
        ]
        assert sorted(checks) == sorted(actual), source_name
        expected.extend(checks)
    assert len(expected) == 27


def test_filtered_unique_preserves_nullable_cemetery_duplicate_rule():
    table = TABLES["BurialSites"]
    index = next(index for index in table.indexes if index.unique)
    ddl = str(CreateIndex(index).compile(dialect=mssql.dialect()))
    assert "CREATE UNIQUE INDEX" in ddl
    assert "WHERE [cemeteryId] IS NOT NULL" in ddl
    assert list(index.columns.keys()) == [
        "cemeteryId", *[f"burialSiteNameSegment{i}" for i in range(1, 6)]
    ]
    # Deletion does not remove the source UNIQUE rule.
    assert "recordDelete_timeMillis" not in ddl


def test_comparison_normalizes_only_default_schema_in_tables_and_foreign_keys():
    comparison = metadata_for_comparison("dbo")
    assert len(comparison.tables) == 41
    assert all(table.schema is None for table in comparison.tables.values())
    foreign_keys = [fk for table in comparison.tables.values() for fk in table.foreign_keys]
    assert len(foreign_keys) == 42
    assert all(fk.column.table.schema is None for fk in foreign_keys)
    assert all(not fk.target_fullname.startswith("dbo.") for fk in foreign_keys)
    assert set(metadata_for_comparison("other_schema").tables) == set(metadata.tables)
    assert all(table.schema == "dbo" for table in metadata.tables.values())


def test_every_table_compiles_for_sql_server():
    for table in metadata.sorted_tables:
        ddl = str(CreateTable(table).compile(dialect=mssql.dialect()))
        assert f"CREATE TABLE dbo.[{table.name}]" in ddl
        assert "VARCHAR(max)" in ddl or all(
            column.info["source_declared_type"] != "TEXT" for column in table.c
        )
        assert "AUTOINCREMENT" not in ddl
        for index in table.indexes:
            assert "CREATE" in str(CreateIndex(index).compile(dialect=mssql.dialect()))


def test_frozen_initial_revision_matches_model_and_avoids_application_imports():
    path = BACKEND / "migrations/versions/0001_sunrise_schema.py"
    assert "from cemaris" not in path.read_text(encoding="utf-8")
    spec = importlib.util.spec_from_file_location("initial_revision", path)
    revision = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(revision)
    dialect = mssql.dialect()
    comparison = sa.MetaData()
    for table in metadata.tables.values():
        table.to_metadata(comparison)
    for key, table in metadata.tables.items():
        historical = revision.metadata.tables[key]
        compatible = comparison.tables[key]
        for column in compatible.c:
            if column.name.endswith(("City", "Province")):
                assert column.type.length == 100
                column.type = historical.c[column.name].type
        # Constraint collections are sets; copying metadata may reorder them.
        def ddl_lines(value):
            return sorted(line.strip().rstrip(",") for line in str(CreateTable(value).compile(dialect=dialect)).splitlines())
        assert ddl_lines(compatible) == ddl_lines(historical)
        assert sorted(str(CreateIndex(index).compile(dialect=dialect)) for index in table.indexes) == sorted(
            str(CreateIndex(index).compile(dialect=dialect)) for index in historical.indexes
        )


def test_alembic_generates_offline_upgrade_and_downgrade_without_database_url():
    upgrade_output = StringIO()
    config = Config(str(BACKEND / "alembic.ini"), output_buffer=upgrade_output)
    command.upgrade(config, "head", sql=True)
    sql = upgrade_output.getvalue()
    assert sql.count("CREATE TABLE dbo.[") == 41
    assert "CREATE TABLE dbo.alembic_version" in sql
    assert "IDENTITY(1,1)" in sql
    assert "NVARCHAR(max) COLLATE Latin1_General_100_BIN2" in sql
    assert "FLOAT(53)" in sql
    assert "WHERE [cemeteryId] IS NOT NULL" in sql
    assert "SunriseSettings" not in sql
    downgrade_output = StringIO()
    config.output_buffer = downgrade_output
    command.downgrade(config, "0001:base", sql=True)
    assert downgrade_output.getvalue().count("DROP TABLE dbo.[") == 41


def test_alembic_detects_real_column_and_foreign_key_drift(sql_connection):
    from conftest import migration_config

    connection, _ = sql_connection
    config = migration_config(connection)
    command.check(config)
    connection.exec_driver_sql(
        "ALTER TABLE dbo.[BurialSiteFields] DROP CONSTRAINT "
        "[fk_BurialSiteFields_burialSiteId_BurialSites]"
    )
    connection.exec_driver_sql(
        "ALTER TABLE dbo.[Users] ADD syntheticMigrationDrift bigint NULL"
    )
    with pytest.raises(AutogenerateDiffsDetected) as drift:
        command.check(config)
    assert "add_fk" in str(drift.value)
    assert "remove_column" in str(drift.value)
