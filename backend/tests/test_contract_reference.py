ALIASES = {"parentCemeteryId": "cemeteryId", "contractIdA": "contractId", "contractIdB": "contractId",
    "notContractId": "contractId", "relatedContractId": "contractId", "notRelatedContractId": "contractId",
    "notWorkOrderId": "workOrderId"}


def insert(connection, name, values):
    table = TABLES[name]
    values = dict(values)
    if "recordCreate_username" in table.c:
        values = {"recordCreate_username": ACTOR, "recordCreate_timeMillis": 1,
            "recordUpdate_username": ACTOR, "recordUpdate_timeMillis": 1, **values}
    result = connection.execute(table.insert().values(**values))
    identity = next((column.name for column in table.c if column.identity is not None), None)
    return (identity, result.inserted_primary_key[0]) if identity else (None, None)


def seed(connection, *, catalogs_only=False):
    maps = {}
    for item in REFERENCE["seed"]:
        if catalogs_only and item["table"] == "Cemeteries":
            break
        values = map_values(item["values"], maps)
        key, actual = insert(connection, item["table"], values)
        if key:
            maps.setdefault(key, {})[item["id"]] = actual
    return maps


def map_values(values, maps):
    return {key: maps.get(ALIASES.get(key, key), {}).get(value, value) for key, value in values.items()}


def form_values(form, maps):
    result = map_values(form, maps)
    if "contractTypeFieldIds" in form:
        field_map = maps["contractTypeFieldId"]
        pieces = form["contractTypeFieldIds"].split(",")
        result["contractTypeFieldIds"] = ",".join(str(field_map.get(int(piece), int(piece))) for piece in pieces if piece)
        for piece in pieces:
            if piece:
                result[f"fieldValue_{field_map.get(int(piece), int(piece))}"] = form.get(f"fieldValue_{piece}", "")
    return result


def normalize(value, maps):
    value = product_boundary(value)
    if isinstance(value, list):
        return [normalize(item, maps) for item in value]
    if isinstance(value, dict):
        return {key: {actual: source for source, actual in maps.get(ALIASES.get(key, key), {}).items()}.get(item, item)
            if not isinstance(item, (dict, list)) else normalize(item, maps) for key, item in value.items()}
    return value


def raw_rows(connection, name, maps, identifier=None):
    table = TABLES[name]
    query = sa.select(table)
    if identifier is not None:
        query = query.where(table.c.contractId == identifier)
    query = query.order_by(*table.primary_key.columns)
    return normalize([{key: value for key, value in row.items() if not key.startswith("record")}
        for row in connection.execute(query).mappings()], maps)


