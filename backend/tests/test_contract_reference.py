def test_original_related_pair_normalization_duplicate_self_and_symmetric_delete(sql_connection):
    connection, _ = sql_connection
    maps = seed(connection, catalogs_only=True)
    maps["contractId"] = {number: add_contract(connection,
        {**form_values(REFERENCE["defaults"][0]["form"], maps), "contractNumber": f"SYN-REL-{number}"}, ACTOR,
        options=OPTIONS, current_date=REFERENCE["today"]) for number in (1, 2, 3)}
    for case in REFERENCE["relationships"]["attempts"]:
        # Decimal coercion is checked separately on SQL IDs, which need not be 1--3.
        a, b = int(float(case["a"])), int(float(case["b"]))
        form = {"contractId": str(maps["contractId"][a]) + (".9" if isinstance(case["a"], str) else ""),
            "relatedContractId": str(maps["contractId"][b]) + (".9" if isinstance(case["b"], str) else "")}
        if "error" in case:
            with pytest.raises((ValueError, IntegrityError)), connection.begin_nested():
                mutate_related_contract(connection, "add", form)
        else:
            assert mutate_related_contract(connection, "add", form) == case["success"]
    assert raw_rows(connection, "RelatedContracts", maps) == REFERENCE["relationships"]["rows"]
    assert mutate_related_contract(connection, "delete", {"contractId": maps["contractId"][3], "relatedContractId": maps["contractId"][1]})
    assert raw_rows(connection, "RelatedContracts", maps) == REFERENCE["relationships"]["afterDelete"]
