def product_boundary(value):
    """Ignore only removed integration fields and their old audit deltas.

    Archived columns may still be read, but no current mutation consumes them.
    Every remaining field, relationship, calculation and audit payload is compared.
    """
    if isinstance(value, list):
        return [product_boundary(item) for item in value
            if not isinstance(item, dict) or item.get("updateField") not in RETIRED_FIELDS]
    if isinstance(value, dict):
        return {key: product_boundary(item) for key, item in value.items() if key not in RETIRED_FIELDS}
    return value


REFERENCE = product_boundary(json.loads((Path(__file__).parent / "fixtures/contracts-reference.json").read_text(encoding="utf-8")))
ACTOR = "synthetic-contracts"
