async function api(url, body, target = page, status = 200) {
  const response = await target.evaluate(async ({ url, body }) => {
    const session = await (await fetch('/api/session')).json()
    const value = await fetch(url, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': session.csrfToken }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) })
    const text = await value.text(); let result; try { result = JSON.parse(text) } catch { result = text }
    return { status: value.status, body: result }
  }, { url, body })
  assert.equal(response.status, status, JSON.stringify(response.body))
  return response.body
}
async function post(name, click) {
  const url = name.startsWith('/') ? name : prefix + name
  const pending = page.waitForResponse(response => new URL(response.url()).pathname === url && response.request().method() === 'POST')
  await click(); const response = await pending
  assert.equal(response.status(), 200, await response.text())
  const body = await response.json(); assert.notEqual(body.success, false, JSON.stringify(body)); return body
}
